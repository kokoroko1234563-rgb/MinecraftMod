package io.github.kokoroko1234563.axiomatic.progress;

import java.util.Optional;
import java.util.function.Supplier;

import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;

import io.github.kokoroko1234563.axiomatic.Axiomatic;
import net.minecraft.advancements.criterion.ContextAwarePredicate;
import net.minecraft.advancements.criterion.EntityPredicate;
import net.minecraft.advancements.criterion.SimpleCriterionTrigger;
import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.Registries;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.server.level.ServerPlayer;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.registries.DeferredRegister;

/**
 * Advancements for mathematical milestones: machines report them, and every player near the
 * machine gets the matching "axiomatic:milestone" criterion. The tree is in
 * data/axiomatic/advancement (generated by tools/gen_assets.py).
 */
public final class Milestones {
    private Milestones() {}

    public static final String NUMERAL = "numeral";
    public static final String CERTIFIED = "certified";
    public static final String DEFINED = "defined";
    public static final String PROVEN = "proven";
    public static final String INDUCTION = "induction";
    public static final String NAMED = "named";
    public static final String CONJECTURE = "conjecture";
    public static final String DISASTER = "disaster";
    public static final String PRIME_FORGED = "prime_forged";
    public static final String STRUCTURE = "structure";
    public static final String IMPLEMENTED = "implemented";
    public static final String GENERAL_RECURSION = "general_recursion";

    /** Players this close to the machine are credited. */
    private static final double RANGE = 24;

    private static final DeferredRegister<net.minecraft.advancements.CriterionTrigger<?>> TRIGGERS =
            DeferredRegister.create(Registries.TRIGGER_TYPE, Axiomatic.MODID);

    public static final Supplier<Trigger> TRIGGER = TRIGGERS.register("milestone", Trigger::new);

    public static void register(IEventBus bus) {
        TRIGGERS.register(bus);
    }

    /** Credits players near {@code pos} with a milestone. */
    public static void award(ServerLevel level, BlockPos pos, String milestone) {
        for (ServerPlayer player : level.players()) {
            if (player.blockPosition().closerThan(pos, RANGE)) {
                TRIGGER.get().trigger(player, milestone);
            }
        }
    }

    /** The "axiomatic:milestone" criterion: {"milestone": "proven"}. */
    public static final class Trigger extends SimpleCriterionTrigger<Trigger.Instance> {
        @Override
        public Codec<Instance> codec() {
            return Instance.CODEC;
        }

        public void trigger(ServerPlayer player, String milestone) {
            trigger(player, instance -> instance.milestone().equals(milestone));
        }

        public record Instance(Optional<ContextAwarePredicate> player, String milestone) implements SimpleInstance {
            public static final Codec<Instance> CODEC = RecordCodecBuilder.create(i -> i.group(
                    EntityPredicate.ADVANCEMENT_CODEC.optionalFieldOf("player").forGetter(Instance::player),
                    Codec.STRING.fieldOf("milestone").forGetter(Instance::milestone)).apply(i, Instance::new));
        }
    }
}
